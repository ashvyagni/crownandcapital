import { expect, test, type Page } from '@playwright/test'

async function enter(page: Page) {
  await page.goto('/')
  await page.getByRole('button', { name: 'Enter the city' }).first().click()
}
async function deed(page: Page) {
  for (let i = 0; i < 16; i++) {
    await page.getByRole('button', { name: /Roll the dice/ }).click()
    const card = page.getByRole('dialog')
    await expect(card).toBeVisible()
    if (await card.getByRole('button', { name: /Acquire/ }).count()) return card
    await card.getByRole('button', { name: /End turn/ }).click()
  }
  throw Error('No available deed reached')
}

test('reload retains unfinished purchase and the committed ownership exactly once', async ({ page }) => {
  await enter(page)
  const card = await deed(page)
  const name = await card.getByRole('heading').textContent()
  await page.reload()
  const restored = page.getByRole('dialog')
  await expect(restored.getByRole('heading')).toHaveText(name!)
  await restored.getByRole('button', { name: /Acquire/ }).click()
  const balance = await restored.locator('.landing-actor b').textContent()
  await page.reload()
  await expect(page.getByRole('dialog').getByText(/Your deed/)).toBeVisible()
  await expect(page.getByRole('dialog').locator('.landing-actor b')).toHaveText(balance!)
  await expect(page.getByRole('dialog').getByRole('button', { name: /Acquire/ })).toHaveCount(0)
  await page.getByRole('dialog').getByRole('button', { name: /End turn/ }).click()
  await expect(page.getByRole('button', { name: /Roll the dice/ })).toBeEnabled()
})

