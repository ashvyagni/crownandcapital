test('audio is opt-in, creates cues after a gesture, and keeps the volume preference', async ({ page }) => {
  await page.addInitScript(() => {
    const original = AudioContext.prototype.createOscillator
    ;(window as unknown as { toneCount: number }).toneCount = 0
    AudioContext.prototype.createOscillator = function () { (window as unknown as { toneCount: number }).toneCount++; return original.call(this) }
  })
  await enter(page)
  await page.getByRole('button', { name: 'Open local profile' }).click()
  const profile = page.getByRole('dialog')
  await expect(profile.getByRole('button', { name: 'Sound off', exact: true })).toHaveAttribute('aria-pressed', 'false')
  expect(await page.evaluate(() => (window as unknown as { toneCount: number }).toneCount)).toBe(0)
  await profile.getByRole('button', { name: 'Sound off', exact: true }).click()
  await profile.getByRole('slider', { name: 'Volume' }).fill('25')
  await profile.getByRole('button', { name: 'Play sound preview' }).click()
  await expect.poll(() => page.evaluate(() => (window as unknown as { toneCount: number }).toneCount)).toBeGreaterThan(0)
  await page.reload()
  await page.getByRole('button', { name: 'Open local profile' }).click()
  await expect(page.getByRole('slider', { name: 'Volume' })).toHaveValue('25')
  await expect(page.getByRole('button', { name: 'Sound on', exact: true })).toHaveAttribute('aria-pressed', 'true')
})

test('two isolated browsers join, see the same authoritative turn and reclaim after reload', async ({ browser }, testInfo) => {
  test.setTimeout(120_000)
  const a = await browser.newContext()
  const b = await browser.newContext()
  const host = await a.newPage(); const guest = await b.newPage()
  try {
    await host.goto('/'); await guest.goto('/')
    await host.getByRole('button', { name: 'Online table', exact: true }).click()
    await host.getByRole('textbox', { name: 'Your online name' }).fill('Online Alice')
    await host.getByRole('button', { name: 'Create online room' }).click()
    const code = host.getByRole('status', { name: 'Room code', exact: true })
    await expect(code).toBeVisible()
    const roomCode = await code.textContent()
    await test.step('guest joins the host room', async () => {
      await guest.getByRole('button', { name: 'Online table', exact: true }).click()
      await guest.getByRole('textbox', { name: 'Your online name' }).fill('Online Bob')
      await guest.getByRole('textbox', { name: 'Room code', exact: true }).fill(roomCode!)
      await guest.getByRole('button', { name: 'Join online room' }).click()
      await expect(host.locator('.online-seats')).toContainText('Online Bob')
    })
    await host.getByRole('button', { name: 'Start online game' }).click()
    await expect(host.getByRole('button', { name: /Roll the dice/ })).toBeEnabled()
    await expect(guest.getByRole('button', { name: /Roll the dice/ })).toBeDisabled()
    await host.getByRole('button', { name: /Roll the dice/ }).click()
    await expect(host.getByRole('dialog')).toBeVisible()
    const landing = await host.getByRole('dialog').getByRole('heading').textContent()
    await expect(guest.getByRole('dialog').getByRole('heading')).toHaveText(landing!)
    await host.reload()
    await expect(host.getByRole('dialog').getByRole('heading')).toHaveText(landing!)
    await expect(host.locator('.connection-banner')).toContainText('connected')
    const pass = host.getByRole('dialog').getByRole('button', { name: 'Pass', exact: true })
    if (await pass.count()) await pass.click()
    else await host.getByRole('dialog').getByRole('button', { name: /End turn/ }).click()
    await expect(guest.getByRole('button', { name: /Roll the dice/ })).toBeEnabled()
    await expect(host.getByRole('button', { name: /Roll the dice/ })).toBeDisabled()
    await host.screenshot({ path: testInfo.outputPath('online-table.png') })
    await host.getByRole('button', { name: 'Open local profile' }).click()
    await host.getByRole('dialog').getByRole('button', { name: /^Online table/ }).click()
    await host.getByRole('button', { name: 'Return to local play', exact: true }).click()
    await host.reload()
    await expect(host.getByRole('button', { name: 'Online table', exact: true })).toBeVisible()
    await host.getByRole('button', { name: 'Online table', exact: true }).click()
    await host.getByRole('button', { name: 'Resume my room' }).click()
    await expect(host.locator('.connection-banner')).toContainText('You are Online Alice')
    await expect(host.getByRole('button', { name: /Roll the dice/ })).toBeDisabled()
  } catch (cause) {
    await guest.screenshot({ path: testInfo.outputPath('guest-failure.png') }).catch(() => {})
    throw cause
  } finally { await a.close().catch(() => {}); await b.close().catch(() => {}) }
})

